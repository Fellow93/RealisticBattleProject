using System;
using System.Collections.Generic;
using System.IO;
using System.Xml;
using HarmonyLib;
using TaleWorlds.GauntletUI.PrefabSystem;

namespace RBMCampaign
{
    /// <summary>
    /// Adds the mercenary companies' gold to the army management screen by editing the native prefabs as they
    /// load (docs/BannerlordGauntletUI.md §8, as ItemWeightPrefabPatch does): a hire price under the party name
    /// in each party-list row (<c>GatherArmyTuple.xml</c> -- SandBox's, or War Sails' override of it, whichever
    /// the factory resolved), and the cart's gold total beside the strength total (<c>ArmyManagement.xml</c>).
    /// The ArmyManagement movie ships codegen'd (SandBox.GauntletUI.AutoGenerated.1.dll), so its generated
    /// prefab is refused first and the whole tree loads from xml. A missing anchor skips that addition rather
    /// than breaking the screen. Decided once per file at first load; a config change needs a restart.
    /// </summary>
    public static class MercenaryArmyPrefabPatch
    {
        private const string MovieName = "ArmyManagement";
        private const string TupleFileName = "GatherArmyTuple.xml";
        private const string ScreenFileName = "ArmyManagement.xml";

        private static readonly Dictionary<string, string> _patchedPaths = new Dictionary<string, string>();

        public static bool IsEnabled
        {
            get { return MercenaryCompanies.IsEnabled; }
        }

        /// <summary>Must run from OnSubModuleLoad: Gauntlet caches a parsed prefab for good.</summary>
        public static void ApplyEarly(Harmony harmony)
        {
            try
            {
                harmony.CreateClassProcessor(typeof(SkipGeneratedArmyManagementPrefab)).Patch();
                harmony.CreateClassProcessor(typeof(RedirectArmyManagementPrefabs)).Patch();
                SpoilsLog.Trace("installed the mercenary army screen load hook");
            }
            catch (Exception exception)
            {
                SpoilsLog.Trace("FAILED to install the mercenary army screen hook: " + exception);
            }
        }

        [HarmonyPatch(typeof(GeneratedPrefabContext))]
        [HarmonyPatch("InstantiatePrefab")]
        private class SkipGeneratedArmyManagementPrefab
        {
            private static bool Prefix(string prefabName, ref GeneratedPrefabInstantiationResult __result)
            {
                if (!IsEnabled || prefabName != MovieName)
                {
                    return true;
                }
                __result = null;
                return false;
            }
        }

        [HarmonyPatch(typeof(WidgetPrefab))]
        [HarmonyPatch("LoadFrom")]
        private class RedirectArmyManagementPrefabs
        {
            private static void Prefix(ref string path)
            {
                string fileName = EndsWithFile(path, TupleFileName) ? TupleFileName
                    : EndsWithFile(path, ScreenFileName) ? ScreenFileName : null;
                if (fileName == null || !IsEnabled)
                {
                    return;
                }
                MercenaryArmyWidgets.RegisterWidgetTypes();
                string patched = GetPatchedPrefabPath(fileName, path);
                if (patched != null)
                {
                    path = patched;
                }
            }
        }

        private static bool EndsWithFile(string path, string fileName)
        {
            return path != null && (path.EndsWith("/" + fileName, StringComparison.OrdinalIgnoreCase)
                || path.EndsWith("\\" + fileName, StringComparison.OrdinalIgnoreCase));
        }

        private static string GetPatchedPrefabPath(string fileName, string originalPath)
        {
            string cached;
            if (_patchedPaths.TryGetValue(fileName, out cached))
            {
                return cached;
            }
            _patchedPaths[fileName] = null;
            try
            {
                XmlDocument document = new XmlDocument();
                document.Load(originalPath);
                bool patched = fileName == TupleFileName ? PatchTuple(document) : PatchScreen(document);
                if (!patched)
                {
                    return null;
                }
                string directory = Path.Combine(Path.GetTempPath(), "RBM", "Prefabs");
                Directory.CreateDirectory(directory);
                string patchedPath = Path.Combine(directory, fileName);
                document.Save(patchedPath);
                _patchedPaths[fileName] = patchedPath;
                SpoilsLog.Trace("injected the mercenary hire gold, redirected " + fileName + " to " + patchedPath);
            }
            catch (Exception exception)
            {
                SpoilsLog.Trace("failed to inject the mercenary hire gold into " + fileName + ": " + exception);
                _patchedPaths[fileName] = null;
            }
            return _patchedPaths[fileName];
        }

        /// <summary>
        /// The price line goes on the row's root button, under the party name: the name cell starts after the
        /// portrait (3 + 112) and its own 4px margin, 167 wide, in both SandBox's row and War Sails' (which only
        /// adds a ship column further right). It accepts no events, so the row stays the click target.
        /// </summary>
        private static bool PatchTuple(XmlDocument document)
        {
            XmlElement root = null;
            XmlNode window = document.SelectSingleNode("/Prefab/Window");
            if (window != null)
            {
                foreach (XmlNode node in window.ChildNodes)
                {
                    if (node is XmlElement element)
                    {
                        root = element;
                        break;
                    }
                }
            }
            XmlElement children = root?["Children"];
            if (root == null || children == null || root.Name != "GatherArmyTupleButtonWidget")
            {
                SpoilsLog.Trace("the army list row prefab does not look as expected; skipping the mercenary price.");
                return false;
            }
            XmlElement price = document.CreateElement(nameof(RBMMercenaryHirePriceWidget));
            price.SetAttribute("Id", "RBMMercenaryHirePrice");
            price.SetAttribute("DoNotAcceptEvents", "true");
            price.SetAttribute("WidthSizePolicy", "Fixed");
            price.SetAttribute("HeightSizePolicy", "Fixed");
            // Wider than the 167px name cell: the price line ("Hire N, then N/day") runs on under the clan banner
            // cell, whose banner sits at the top of the row.
            price.SetAttribute("SuggestedWidth", "240");
            price.SetAttribute("SuggestedHeight", "22");
            price.SetAttribute("HorizontalAlignment", "Left");
            price.SetAttribute("VerticalAlignment", "Bottom");
            price.SetAttribute("MarginLeft", "119");
            price.SetAttribute("MarginBottom", "6");
            price.SetAttribute("Brush", "ArmyManagement.Army.Tuple.Value");
            price.SetAttribute("Brush.FontSize", "15");
            price.SetAttribute("Brush.TextHorizontalAlignment", "Left");
            price.SetAttribute("Clan", "@Clan");
            children.AppendChild(price);
            return true;
        }

        /// <summary>
        /// The cart gold line goes bottom-left, mirroring the strength total's bottom-right placement, as a
        /// sibling of that total so it sits in the same plain container.
        /// </summary>
        private static bool PatchScreen(XmlDocument document)
        {
            XmlElement strength = null;
            foreach (XmlNode node in document.GetElementsByTagName("TextWidget"))
            {
                if (node is XmlElement element && element.GetAttribute("IntText") == "@TotalStrength")
                {
                    strength = element;
                    break;
                }
            }
            // TextWidget -> <Children> -> the strength ListPanel -> its container's <Children>.
            XmlNode strengthPanel = strength?.ParentNode?.ParentNode;
            XmlNode container = strengthPanel?.ParentNode;
            if (strengthPanel == null || container == null)
            {
                SpoilsLog.Trace("the army management prefab does not look as expected; skipping the mercenary cart gold.");
                return false;
            }
            XmlElement gold = document.CreateElement(nameof(RBMMercenaryCartGoldWidget));
            gold.SetAttribute("Id", "RBMMercenaryCartGold");
            gold.SetAttribute("DoNotAcceptEvents", "true");
            gold.SetAttribute("WidthSizePolicy", "CoverChildren");
            gold.SetAttribute("HeightSizePolicy", "Fixed");
            gold.SetAttribute("SuggestedHeight", "35");
            gold.SetAttribute("HorizontalAlignment", "Left");
            gold.SetAttribute("VerticalAlignment", "Bottom");
            gold.SetAttribute("MarginBottom", "45");
            gold.SetAttribute("MarginLeft", "75");
            gold.SetAttribute("Brush", "ArmyManagement.Army.TotalCostAndStrength.Title");
            container.InsertAfter(gold, strengthPanel);
            return true;
        }
    }
}
